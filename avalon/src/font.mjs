const FONTS = { small: { glyphs: SMALL, h: 5 }, big: { glyphs: BIG, h: 7 } };

/** Normalise: uppercase, strip accents except Ö (drawn where a font has it), keep known symbols. */
export function norm(str) {
  return String(str).toUpperCase().replace(/Ö/g, '\u0001').normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/\u0001/g, 'Ö');
}

function glyph(font, ch) {
  const g = FONTS[font].glyphs;
  if (ch === 'Ö' && !g[ch]) ch = 'O';
  return g[ch] || g['?'] || g[' '];
}

/** Width in pixels of a string (no trailing spacing). */
export function measure(str, { font = 'small', bold = false, spacing = 1 } = {}) {
  const s = [...norm(str)];
  if (!s.length) return 0;
  let w = 0;
  for (const ch of s) w += glyph(font, ch)[0].length + (bold ? 1 : 0) + spacing;
  return w - spacing;
}

/** Truncate with '..' so the string fits maxW pixels. */
export function fit(str, maxW, opts = {}) {
  let s = norm(str);
  if (measure(s, opts) <= maxW) return s;
  while (s.length > 1 && measure(s + '..', opts) > maxW) s = s.slice(0, -1);
  return s.replace(/[\s.\-_]+$/, '') + '..';
}

/**
 * Draw text. color may be a key or fn(row, col) -> key (for gradients).
 * Options: outline (8-neighbour ring), shadow (offset +1,+1), bold (thicken right).
 * Returns the advance width.
 */
export function text(r, str, x, y, { font = 'small', color = '#ffffff', shadow = null, outline = null, bold = false, spacing = 1 } = {}) {
  const s = [...norm(str)];
  const pts = [];
  let cx = x;
  for (const ch of s) {
    const g = glyph(font, ch);
    g.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) {
        if (row[i] !== '#') continue;
        pts.push([cx + i, y + j, j, cx + i - x]);
        if (bold) pts.push([cx + i + 1, y + j, j, cx + i + 1 - x]);
      }
    });
    cx += g[0].length + (bold ? 1 : 0) + spacing;
  }
  if (outline) {
    for (const [px, py] of pts) {
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) r.set(px + dx, py + dy, outline);
    }
  }
  if (shadow) for (const [px, py] of pts) r.set(px + 1, py + 1, shadow);
  for (const [px, py, row, col] of pts) r.set(px, py, typeof color === 'function' ? color(row, col) : color);
  return cx - x - spacing;
}

